import { classify, compileCustomPatterns, isAutoGenerated, shouldPreserve } from "./classify.js";
import type { ExtractedComment } from "./comment.js";
import type { Config } from "./config.js";
import {
  dominantEol,
  hasMixedEol,
  joinLines,
  rebuildEols,
  splitLines,
  type EolStyle,
} from "./eol.js";
import { lex, looksLikeJsx, type Language } from "./lex/index.js";
import { restore, type ResolvedComment } from "./restore.js";
import { strip, type SpanWithClass } from "./strip.js";

export type SkipReason =
  | "auto-generated"
  | "jsx"
  | "mixed-eol"
  | "verify-failed"
  | "unsupported-encoding";

export const SKIP_EXPLANATIONS: Record<SkipReason, string> = {
  "auto-generated": "marked <auto-generated>; its generator rewrites it wholesale",
  jsx: "contains JSX, where // is literal text rather than a comment",
  "mixed-eol": "mixes CRLF and LF line endings, which cannot be rebuilt byte-exactly",
  "verify-failed": "failed its round-trip check, so it was left untouched",
  "unsupported-encoding": "uses an encoding Sideline cannot re-emit",
};

/**
 * Line-ending facts about a file, carried in the store.
 *
 * Kept explicitly rather than re-derived on restore because a file stripped
 * down to nothing has no terminators left to infer from.
 */
export interface EolMeta {
  eol: EolStyle;
  /** The original file's final terminator: `"\n"`, `"\r\n"`, or `""`. */
  trailing: string;
}

export interface StripTextResult {
  ok: true;
  text: string;
  comments: ExtractedComment[];
  meta: EolMeta;
  /** Comments deliberately left in the code. Reported, never stored. */
  preservedCount: number;
}

export type ExtractOutcome = StripTextResult | { ok: false; reason: SkipReason };

/** Convert stored/extracted comments into restorer input. */
export function toResolved(comments: readonly ExtractedComment[]): ResolvedComment[] {
  return comments.map((c) => ({
    placement: c.placement,
    at: c.at,
    line: c.line,
    indent: c.indent,
    text: c.text,
    blankAbove: c.blankAbove,
    blankBelow: c.blankBelow,
    stripCol: c.stripCol,
    sepLen: c.sepLen,
    padBefore: c.padBefore,
    padAfter: c.padAfter,
  }));
}

/**
 * Lift the extractable comments out of one file's text.
 *
 * Every extraction is verified by rebuilding the original in memory and
 * comparing it character for character. A lexer bug therefore costs a skipped
 * file and a warning rather than corrupted source, which is the only acceptable
 * failure mode for a tool that rewrites code in place.
 */
export function stripText(
  source: string,
  language: Language,
  config: Config,
  options: { verify?: boolean; isJsFile?: boolean } = {},
): ExtractOutcome {
  const verify = options.verify ?? true;
  const { lines, lineEols } = splitLines(source);

  if (hasMixedEol(lineEols)) return { ok: false, reason: "mixed-eol" };
  if (config.skipAutoGenerated && isAutoGenerated(lines)) {
    return { ok: false, reason: "auto-generated" };
  }

  const text = lines.join("\n");
  if (options.isJsFile && looksLikeJsx(text)) return { ok: false, reason: "jsx" };

  const meta: EolMeta = {
    eol: dominantEol(lineEols),
    trailing: lineEols.length > 0 ? lineEols[lineEols.length - 1]! : "",
  };

  const spans = lex(language, text);
  const custom = compileCustomPatterns(config);

  const extractable: SpanWithClass[] = [];
  let preservedCount = 0;
  let seenFirst = false;

  for (const span of spans) {
    const cls = classify(span, { isFirstInFile: !seenFirst });
    seenFirst = true;
    if (shouldPreserve(span, cls, config, custom)) {
      preservedCount++;
      continue;
    }
    extractable.push({ span, cls });
  }

  const result = strip(lines, extractable, config.anchorWindow);
  const stripped = joinLines(result.lines, rebuildEols(result.lines.length, meta.eol, meta.trailing));

  if (verify) {
    const rebuilt = restoreText(stripped, toResolved(result.comments), meta);
    if (rebuilt !== source) return { ok: false, reason: "verify-failed" };
  }

  return { ok: true, text: stripped, comments: result.comments, meta, preservedCount };
}

/** Put comments back into stripped text, re-emitting the original terminators. */
export function restoreText(
  strippedSource: string,
  comments: readonly ResolvedComment[],
  meta: EolMeta,
): string {
  const { lines } = splitLines(strippedSource);
  const restored = restore(lines, comments);
  return joinLines(restored, rebuildEols(restored.length, meta.eol, meta.trailing));
}
