import type { CommentClass, CommentSpan } from "./comment.js";
import type { Config } from "./config.js";

/**
 * Directives whose removal changes what the compiler, linter or bundler does.
 *
 * Tested against the comment text with leading whitespace trimmed. This list is
 * deliberately conservative — a false positive only means a comment stays in
 * the code, whereas a false negative can silently change build output.
 */
const PRAGMA_PATTERNS: RegExp[] = [
  /^#!/, // shebang
  /^\/\/\s*@ts-(?:ignore|expect-error|nocheck|check)\b/,
  /^\/\/\/\s*<reference\b/,
  /^\/[/*]\s*eslint\b/,
  /^\/[/*]\s*eslint-(?:disable|enable)/,
  /^\/[/*]\s*globals?\b/,
  /^\/[/*]\s*prettier-ignore\b/,
  /^\/[/*]\s*(?:istanbul|c8|v8)\s+ignore\b/,
  /^\/\/\s*#\s*source(?:MappingURL|URL)=/,
  /^\/\*\s*webpack[A-Z]\w*\s*:/,
  /^\/[/*]\s*@jsx(?:ImportSource|Runtime|Frag)?\b/,
  /^\/\/\s*noinspection\b/,
  /^\/\/\s*ReSharper\s+(?:disable|restore)\b/,
  /^\/[/*]\s*@formatter:(?:off|on)\b/,
  /^\/\/\s*<auto-generated/,
  /^\/[/*]\s*@vite-ignore\b/,
  /^\/[/*]\s*@__PURE__\b/,
  /^\/[/*]\s*deno-lint-ignore\b/,
  /^\/[/*]\s*biome-ignore\b/,
];

const REGION_PATTERN = /^\/\/\s*#?(?:region|endregion)\b/i;

/**
 * Minifier directives meaning "keep this in the output". Classed as `license`
 * rather than `pragma` because they do not break a build, they only affect what
 * survives minification — so they follow the license preserve setting.
 */
const LICENSE_DIRECTIVE = /@(?:license|preserve)\b/;

const LICENSE_TEXT = /\b(?:copyright|licen[cs]e|SPDX-License-Identifier)\b|©|\(c\)\s*\d{4}/i;

const AUTO_GENERATED = /^\s*(?:\/\/|\/\*|\*)\s*<auto-generated/;

export interface ClassifyContext {
  /** True for the first comment in the file, which may be a license header. */
  isFirstInFile: boolean;
}

export function classify(span: CommentSpan, ctx: ClassifyContext): CommentClass {
  const text = span.text;
  const trimmed = text.trimStart();

  if (REGION_PATTERN.test(trimmed)) return "region";
  if (PRAGMA_PATTERNS.some((re) => re.test(trimmed))) return "pragma";
  if (LICENSE_DIRECTIVE.test(text)) return "license";
  if (ctx.isFirstInFile && LICENSE_TEXT.test(text)) return "license";

  // XML doc comments, then JSDoc. `/**/` is an empty block, not a doc comment.
  if (/^\/\/\//.test(trimmed)) return "doc";
  if (/^\/\*\*(?!\/)/.test(trimmed)) return "doc";

  return "ordinary";
}

/** True when this comment should be left in the code rather than extracted. */
export function shouldPreserve(
  span: CommentSpan,
  cls: CommentClass,
  config: Config,
  customPatterns: readonly RegExp[],
): boolean {
  if (customPatterns.some((re) => re.test(span.text))) return true;

  switch (cls) {
    case "pragma":
      return config.preserve.pragma;
    case "region":
      return config.preserve.region;
    case "doc":
      return config.preserve.doc;
    case "license":
      return config.preserve.license;
    case "ordinary":
      return false;
  }
}

export function compileCustomPatterns(config: Config): RegExp[] {
  return config.preserve.custom.map((src) => new RegExp(src));
}

/**
 * Detect generated files, which are rewritten wholesale by their generator and
 * so must not have comments lifted out of them.
 */
export function isAutoGenerated(lines: readonly string[]): boolean {
  const limit = Math.min(lines.length, 10);
  for (let i = 0; i < limit; i++) {
    if (AUTO_GENERATED.test(lines[i]!)) return true;
  }
  return false;
}
