import fs from "node:fs";
import path from "node:path";
import { parse as parseYaml } from "yaml";

export interface PreserveConfig {
  /** Directives that change compiler/linter behaviour. Preserved by default. */
  pragma: boolean;
  /** `//#region` / `//#endregion` folding markers. Preserved by default. */
  region: boolean;
  /** XML doc comments and JSDoc. Extracted by default. */
  doc: boolean;
  /** Copyright / SPDX / `@license` blocks. Extracted by default. */
  license: boolean;
  /** Extra regex sources; a comment matching any of them stays in the code. */
  custom: string[];
}

export interface Config {
  include: string[];
  exclude: string[];
  store: string;
  anchorWindow: number;
  fuzzyThreshold: number;
  preserve: PreserveConfig;
  /** Skip files marked `// <auto-generated>` entirely. */
  skipAutoGenerated: boolean;
}

